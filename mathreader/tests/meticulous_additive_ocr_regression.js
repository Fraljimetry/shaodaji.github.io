'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const core = fs.readFileSync(path.join(root, 'js/00-core.js'), 'utf8');
const index = fs.readFileSync(path.join(root, 'js/41-equations-bibliography.js'), 'utf8');
const helper = core.match(/function mergePageIndexOcrEvidence\(existing, incoming, nativeLines = \[\]\) \{[\s\S]*?\n\}\n/);
assert.ok(helper, 'additive merge helper exists');
const merge = vm.runInNewContext(`(${helper[0]})`);
const line = (text, ratio, xStartRatio = 0.1) => ({text, ratio, xStartRatio});
const before = {lines:[line('Theorem 1.1',.1)],words:[],equationMarginEvidence:[{page:2,label:'(1.4)',ratio:.8}]};
const after = {lines:[line('Theorem 1.1',.1),line('Equation (1.5)',.45)],words:[],equationMarginEvidence:[{page:2,label:'(1.7)',ratio:.9}]};
const got = merge(before,after,[line('References',.7)]);
assert.equal(got.lines.length,3,'duplicates removed; old, native and new lines survive');
assert.deepEqual([...got.equationMarginEvidence].map(x=>x.label),['(1.4)','(1.7)']);
const repeat = merge(got,after,[line('References',.7)]);
assert.equal(repeat.lines.length,3,'rerunning OCR is idempotent for lines');
assert.equal(repeat.equationMarginEvidence.length,2,'rerunning OCR is idempotent for margin labels');
const conflict = merge(before,{lines:[line('Theorem I.I',.1)],words:[]});
assert.equal(conflict.lines.length,2,'conflicting recognition retained without overwriting');
assert.match(core,/previousStructure = structureEntries\.slice\(\)/);
assert.match(core,/previousBibliography = bibliographyEntries\.slice\(\)/);
assert.match(core,/previousEquations = new Map\(/);
assert.match(core,/0 removed/);
assert.match(index,/ignoreManual = false/);
console.log('PASS: 10 additive meticulous OCR regression assertions');
