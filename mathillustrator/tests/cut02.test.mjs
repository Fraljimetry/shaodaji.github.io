import test from 'node:test';
import assert from 'node:assert/strict';
import {newDoc,addPoint,append,command,createResolver,validateDoc,clone,affected,remove} from '../src/model.mjs';
import {regularPolygonVertices,worldBounds} from '../src/geometry.mjs';

test('legacy v1 JSON migrates polygon sides without altering prior semantics',()=>{
 const old=newDoc();delete old.settings.polygonSides;
 const migrated=validateDoc(old);
 assert.equal(migrated.settings.polygonSides,6);
 assert.deepEqual(old.objects,[]);
});
test('regular polygon has live center and vertex, exact side count, area and bounds',()=>{
 const d=newDoc(),a=command(d,'A=(1,2)'),b=command(d,'B=(3,2)');
 const shape=command(d,'RegularPolygon(A,B,4)');
 assert.equal(shape.sides,4);
 assert.equal(validateDoc(d).objects.length,3);
 let vertices=regularPolygonVertices(...createResolver(d).points(shape),shape.sides);
 assert.equal(vertices.length,4);
 assert.ok(Math.abs(vertices[2][0]+1)<1e-10&&Math.abs(vertices[2][1]-2)<1e-10);
 assert.deepEqual(worldBounds(d,createResolver(d)),{minX:-1,maxX:3,minY:0,maxY:4});
 b.xy=[1,4];vertices=regularPolygonVertices(...createResolver(d).points(shape),shape.sides);
 assert.ok(Math.abs(vertices[0][0]-1)<1e-10&&Math.abs(vertices[0][1]-4)<1e-10);
});
test('regular polygon rejects degeneracies and malformed imported side counts',()=>{
 const d=newDoc();command(d,'A=(0,0)');command(d,'B=(0,0)');
 for(const cmd of ['RegularPolygon(A,B,4)','RegularPolygon(A,A,6)','RegularPolygon(A,B,2)','RegularPolygon(A,B,101)','RegularPolygon(A,B,-5)'])assert.throws(()=>command(d,cmd));
 command(d,'C=(2,0)');const shape=command(d,'RegularPolygon(A,C,6)');
 for(const value of [0,2,2.5,101,'6',null]){const bad=clone(d);bad.objects.find(o=>o.id===shape.id).sides=value;assert.throws(()=>validateDoc(bad));}
 const bad=clone(d);bad.settings.polygonSides=2;assert.throws(()=>validateDoc(bad));
});
test('append failure from autogenerated name collision leaves counters and data unchanged',()=>{
 const d=newDoc();addPoint(d,[2,1],'point 2');const before=JSON.stringify(d);
 assert.throws(()=>addPoint(d,[3,2]),/Name already in use/);
 assert.equal(JSON.stringify(d),before);
});
test('transitive dependency graph deletion is linear-style and exact for deep chains and branches',()=>{
 const d=newDoc(),a=addPoint(d,[0,0],'A'),b=addPoint(d,[1,0],'B');let prev=a;
 for(let i=0;i<3200;i++)prev=append(d,{type:'midpoint',refs:[prev.id,b.id]});
 const alt=append(d,{type:'segment',refs:[prev.id,b.id]});
 assert.equal(affected(d,a.id).size,3202);
 assert.equal(remove(d,a.id),3202);
 assert.equal(d.objects.length,1);assert.equal(d.objects[0].id,b.id);
 assert.equal(validateDoc(d).objects.length,1);
});
